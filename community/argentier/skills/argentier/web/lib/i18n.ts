export const LANGS: Lang[] = ["fr", "en", "de", "es", "it"];

/** Locale Intl par langue (formatage monétaire / nombres). */
export const LOCALE: Record<Lang, string> = {
  fr: "fr-FR",
  en: "en-US",
  de: "de-DE",
  es: "es-ES",
  it: "it-IT",
};

export function detectLang(input?: string | null): Lang {
  const s = (input ?? "").toLowerCase();
  if (s.startsWith("de")) return "de";
  if (s.startsWith("es")) return "es";
  if (s.startsWith("it")) return "it";
  if (s.startsWith("fr")) return "fr";
  return "en";
}

// Formatage monétaire selon la langue (nombre localisé, « € » suffixe).
export function eur(n: number, lang: Lang): string {
  return Math.round(n).toLocaleString(LOCALE[lang]) + " €";
}

